    from backend.app import create_app
    from backend.models.user import User
    from backend.models.otp_session import VoterOtpSession
    from backend.services.auth_service import hash_otp
    from backend.extensions import db
    app = create_app()
    with app.app_context():
        divya = User.query.filter_by(voter_id="VTR-2026-00301").first()
        assert divya is not None
        assert divya.registered_mobile == "+91 89198 02993"
        assert divya.constituency == "Bhimili"
        session = VoterOtpSession.query.filter_by(voter_user_id=divya.id, is_verified=False).order_by(VoterOtpSession.created_at.desc()).first()
        assert session is not None
        session.salt = "test_salt_123"
        session.otp_hash = hash_otp("123456", "test_salt_123")
        db.session.commit()

    # 7c. Verify OTP
    status, otp_res = api_call("POST", "/auth/voter/verify-otp", {
        "stage_token": stage_token_1,
        "otp": "123456"
    })
    assert status == 200, f"OTP verification failed: {otp_res}"
    stage_token_2 = otp_res["stage_token"]
    print("[PASS] 7b. Voter Divya OTP verified successfully")

    # 7d. Verify Identity (Demo Fallback or Biometric)
    status, ident_res = api_call("POST", "/auth/voter/verify-identity", {
        "stage_token": stage_token_2,
        "is_demo_fallback": True
    })
    assert status == 200, f"Identity verification failed: {ident_res}"
    divya_jwt = ident_res["token"]
    divya_headers = {"Authorization": f"Bearer {divya_jwt}"}
    print("[PASS] 7c. Voter Divya identity verified, JWT session generated")

