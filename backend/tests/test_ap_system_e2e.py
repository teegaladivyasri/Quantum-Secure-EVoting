    election_id = el_data["election"]["id"]
    print(f"[PASS] 3. Election created with wizard payload (ID: {election_id})")

    # 4. Verify candidate roster and automatic NOTA placement for Bhimili
    status, bhimili_cands = api_call("GET", f"/admin/candidates?election_id={election_id}&constituency_id={bhimili_id}", headers=admin_headers)
    assert status == 200
    b_cands = bhimili_cands["candidates"]
    assert len(b_cands) == 4, f"Expected 4 options in Bhimili (3 + NOTA), got {len(b_cands)}"
    assert b_cands[0]["name"] == "Ganta Srinivasa Rao" and b_cands[0]["ballot_position"] == 1
    assert b_cands[1]["name"] == "Muttamsetti Srinivasa Rao (Avanthi Srinivas)" and b_cands[1]["ballot_position"] == 2
    assert b_cands[2]["name"] == "Addala Venkata Varma Raju" and b_cands[2]["ballot_position"] == 3
    assert b_cands[3]["name"] == "None of the Above (NOTA)" and b_cands[3]["is_nota"] is True and b_cands[3]["ballot_position"] == 4
    print("[PASS] 4. Verified Bhimili roster: Ganta (1) -> Muttamsetti (2) -> Addala (3) -> NOTA (4)")

    # 5. Verify candidate roster and automatic NOTA placement for Bobbili
    status, bobbili_cands = api_call("GET", f"/admin/candidates?election_id={election_id}&constituency_id={bobbili_id}", headers=admin_headers)
    assert status == 200
    bob_cands = bobbili_cands["candidates"]
    assert len(bob_cands) == 4, f"Expected 4 options in Bobbili (3 + NOTA), got {len(bob_cands)}"
    assert bob_cands[0]["name"] == "R. V. S. K. K. Ranga Rao (Baby Nayana)" and bob_cands[0]["ballot_position"] == 1
    assert bob_cands[1]["name"] == "Venkata China Appala Naidu Sambangi" and bob_cands[1]["ballot_position"] == 2
    assert bob_cands[2]["name"] == "Maripi Vidyasagar (Vinay)" and bob_cands[2]["ballot_position"] == 3
    assert bob_cands[3]["name"] == "None of the Above (NOTA)" and bob_cands[3]["is_nota"] is True and bob_cands[3]["ballot_position"] == 4
    print("[PASS] 5. Verified Bobbili roster: Ranga Rao (1) -> Sambangi (2) -> Maripi (3) -> NOTA (4)")

    # 6. Publish and Open Election
    status, _ = api_call("PATCH", f"/admin/elections/{election_id}/status", {"status": "PUBLISHED"}, headers=admin_headers)
    assert status == 200
    status, open_res = api_call("PATCH", f"/admin/elections/{election_id}/status", {"status": "OPEN"}, headers=admin_headers)
    assert status == 200
    assert open_res["election"]["is_active"] is True
    print("[PASS] 6. Election published and opened for live voting")

    # 7. Voter Divya (VTR-2026-00301) Authentication Flow
    # 7a. Initiate Login
    status, init_res = api_call("POST", "/auth/voter/initiate", {"voter_id": "VTR-2026-00301"})
    assert status == 200, f"Voter initiation failed: {init_res}"
    stage_token_1 = init_res["stage_token"]
    assert "stage_token" in init_res
    print(f"[PASS] 7a. Voter Divya login initiated (Masked Mobile: {init_res.get('masked_mobile')})")

