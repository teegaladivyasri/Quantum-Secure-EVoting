    assert "qber_percentage" in telemetry
    assert "sifted_bits" in telemetry
    print(f"[PASS] 9. Divya cast vote with Quantum encryption: QBER={telemetry['qber_percentage']}%, Sifted Bits={telemetry['sifted_bits']}")

