    print("[PASS] 8. Divya ballot strictly isolated to Bhimili assembly candidates + NOTA")

    # 9. Divya Casts Vote for Ganta Srinivasa Rao
    chosen_cand = next(c for c in cands_for_divya if c["name"] == "Ganta Srinivasa Rao")
    status, vote_res = api_call("POST", "/voter/cast-vote", {
        "election_id": election_id,
        "candidate_id": chosen_cand["id"]
    }, headers=divya_headers)
