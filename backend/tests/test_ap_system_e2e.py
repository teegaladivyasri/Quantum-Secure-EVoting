    status, dup_vote = api_call("POST", "/voter/cast-vote", {
        "election_id": election_id,
        "candidate_id": chosen_cand["id"]
    }, headers=divya_headers)
    assert status == 409, f"Expected 409 duplicate vote error, got {status}"
    print("[PASS] 10. Re-voting blocked strictly with 409 CONFLICT")

